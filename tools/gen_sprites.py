#!/usr/bin/env python3
"""Compile art/*.sprite into base/src/assets/anim_assets.{c,h}.

Run from the repo root:  python3 tools/gen_sprites.py   (or: just sprites)

.sprite format (one sprite per file; '#' starts a comment):

    sprite fireball
    palette  1=F80  2=FF0  3=F00        # key=RGB444 hex; '.' is transparent

    clip fly loop                       # loop | once | pingpong
    frame 80                            # milliseconds, optional event=NAME
    ..1..
    .121.
    ...

Every frame of a sprite has the same size. Up to 15 palette colours.
For each sprite NAME the header declares ANIM_NAME (anim_sprite_t) and one
clip constant per clip, e.g. ANIM_FIREBALL_FLY (const anim_clip_t *).
"""

import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, "art")
OUT_C = os.path.join(ROOT, "base", "src", "assets", "anim_assets.c")
OUT_H = os.path.join(ROOT, "base", "src", "assets", "anim_assets.h")
MODES = {"loop": "ANIM_LOOP", "once": "ANIM_ONCE", "pingpong": "ANIM_PINGPONG"}


def fail(path, line, msg):
    sys.exit(f"{os.path.relpath(path, ROOT)}:{line}: {msg}")


def parse(path):
    sprite = {"name": None, "palette": {}, "clips": [], "size": None}
    clip = frame = None
    for n, raw in enumerate(open(path), 1):
        text = raw.split("#", 1)[0].rstrip()
        if not text.strip():
            continue
        words = text.split()
        if words[0] == "sprite":
            sprite["name"] = words[1]
        elif words[0] == "palette":
            for item in words[1:]:
                m = re.fullmatch(r"(\S)=([0-9A-Fa-f]{3})", item)
                if not m or m.group(1) == ".":
                    fail(path, n, f"bad palette entry {item!r} (want K=RGB, e.g. 1=F80)")
                sprite["palette"][m.group(1)] = int(m.group(2), 16)
            if len(sprite["palette"]) > 15:
                fail(path, n, "more than 15 palette colours")
        elif words[0] == "clip":
            if len(words) != 3 or words[2] not in MODES:
                fail(path, n, "want: clip NAME loop|once|pingpong")
            clip = {"name": words[1], "mode": words[2], "frames": []}
            sprite["clips"].append(clip)
        elif words[0] == "frame":
            if clip is None:
                fail(path, n, "frame before any clip")
            event = None
            for w in words[2:]:
                if w.startswith("event="):
                    event = w[6:]
                else:
                    fail(path, n, f"unknown frame option {w!r}")
            frame = {"ms": int(words[1]), "event": event, "rows": [], "line": n}
            clip["frames"].append(frame)
        else:
            if frame is None:
                fail(path, n, "pixel row before any frame")
            row = text.strip()
            for ch in row:
                if ch != "." and ch not in sprite["palette"]:
                    fail(path, n, f"colour {ch!r} not in palette")
            frame["rows"].append(row)
    if not sprite["name"]:
        fail(path, 1, "missing 'sprite NAME'")
    for c in sprite["clips"]:
        if not c["frames"]:
            fail(path, 1, f"clip {c['name']} has no frames")
        for f in c["frames"]:
            widths = {len(r) for r in f["rows"]}
            if len(widths) != 1:
                fail(path, f["line"], "rows of different lengths")
            size = (widths.pop(), len(f["rows"]))
            if sprite["size"] is None:
                sprite["size"] = size
            elif size != sprite["size"]:
                fail(path, f["line"], f"frame is {size[0]}x{size[1]}, sprite is "
                                       f"{sprite['size'][0]}x{sprite['size'][1]}")
    return sprite


def main():
    files = sorted(f for f in os.listdir(ART) if f.endswith(".sprite"))
    sprites = [parse(os.path.join(ART, f)) for f in files]
    events = sorted({f["event"] for s in sprites for c in s["clips"] for f in c["frames"] if f["event"]})

    h = ["// Generated by tools/gen_sprites.py from art/*.sprite -- do not edit.", "",
         "#ifndef ANIM_ASSETS_H", "#define ANIM_ASSETS_H", "", '#include "anim.h"', "",
         "// animation events (frame event=NAME); 0 = none"]
    for i, e in enumerate(events, 1):
        h.append(f"#define ANIM_EVENT_{e.upper()} {i}")
    h.append("")
    c = ["// Generated by tools/gen_sprites.py from art/*.sprite -- do not edit.", "",
         '#include "anim_assets.h"', ""]

    for s in sprites:
        N = s["name"].upper()
        keys = list(s["palette"])
        index = {k: i + 1 for i, k in enumerate(keys)}  # 0 = transparent
        w, hgt = s["size"]
        pal = ", ".join(f"0x{s['palette'][k]:03X}" for k in keys)
        c.append(f"// ---- {s['name']} ({w}x{hgt}) ----")
        c.append(f"static const hub75_color_t {s['name']}_palette[16] = {{0, {pal}}};")
        for ci, clip in enumerate(s["clips"]):
            for fi, f in enumerate(clip["frames"]):
                px = ",".join(str(index.get(ch, 0)) for row in f["rows"] for ch in row)
                c.append(f"static const uint8_t {s['name']}_{clip['name']}_{fi}[] = {{{px}}};")
            frames = ", ".join(f"{s['name']}_{clip['name']}_{fi}" for fi in range(len(clip["frames"])))
            ms = ", ".join(str(f["ms"]) for f in clip["frames"])
            ev = ", ".join(f"ANIM_EVENT_{f['event'].upper()}" if f["event"] else "0" for f in clip["frames"])
            c.append(f"static const uint8_t *const {s['name']}_{clip['name']}_frames[] = {{{frames}}};")
            c.append(f"static const uint16_t {s['name']}_{clip['name']}_ms[] = {{{ms}}};")
            c.append(f"static const uint8_t {s['name']}_{clip['name']}_events[] = {{{ev}}};")
        clips = ",\n    ".join(
            f"{{\"{cl['name']}\", {MODES[cl['mode']]}, {len(cl['frames'])}, {s['name']}_{cl['name']}_frames, "
            f"{s['name']}_{cl['name']}_ms, {s['name']}_{cl['name']}_events}}" for cl in s["clips"])
        c.append(f"static const anim_clip_t {s['name']}_clips[] = {{\n    {clips}\n}};")
        c.append(f"const anim_sprite_t ANIM_{N} = {{\"{s['name']}\", {w}, {hgt}, {s['name']}_palette, "
                 f"{len(s['clips'])}, {s['name']}_clips}};")
        c.append("")
        h.append(f"extern const anim_sprite_t ANIM_{N}; // {w}x{hgt}")
        for ci, clip in enumerate(s["clips"]):
            h.append(f"#define ANIM_{N}_{clip['name'].upper()} (&ANIM_{N}.clips[{ci}])")
        h.append("")
    h.append("#endif // ANIM_ASSETS_H")

    changed = write_if_changed(OUT_C, "\n".join(c) + "\n") | write_if_changed(OUT_H, "\n".join(h) + "\n")
    print(f"{len(sprites)} sprites -> {os.path.relpath(OUT_C, ROOT)}" + ("" if changed else " (unchanged)"))


def write_if_changed(path, text):
    """Only touch the file when its content changes (keeps rebuilds and the
    simulator's file watcher from looping)."""
    if os.path.exists(path) and open(path).read() == text:
        return False
    open(path, "w").write(text)
    return True


if __name__ == "__main__":
    main()

# Arrows use the same codes as the big font (0x18..0x1B).
ARROWS = [
    ("up",    [".#.", "###", ".#.", ".#.", ".#."]),
    ("down",  [".#.", ".#.", ".#.", "###", ".#."]),
    ("right", ["#..", "##.", "###", "##.", "#.."]),
    ("left",  ["..#", ".##", "###", ".##", "..#"]),
]


def row_bits(row):
    assert len(row) == 3 and set(row) <= {"#", "."}, row
    return sum(1 << (2 - i) for i, c in enumerate(row) if c == "#")


def emit(label, rows):
    assert len(rows) == 5, label
    vals = ", ".join(f"0x{row_bits(r):X}" for r in rows)
    print(f"    {vals},  // {label:8} {' '.join(rows)}")



int _write(int file, char *ptr, int len)
{
   (void)file;
   for (int i = 0; i < len; i++){
       if (ptr[i] == '\n'){
           XMC_UART_CH_Transmit(CYBSP_DEBUG_UART_HW, '\r');
       }
       XMC_UART_CH_Transmit(CYBSP_DEBUG_UART_HW, ptr[i]);
   }
   return len;
}

